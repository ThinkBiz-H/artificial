import {
  Hand,
  Droplet,
  ShieldCheck,
  Gem,
  Package,
  Heart,
  Sparkles,
  PenTool,
  Palette,
  Layers,
  PackageCheck,
  Clock,
  Flame,
  Wand2,
  Truck,
  SprayCan,
  Settings2,
  BadgeCheck,
  RotateCcw,
  Headset,
  Crown,
  Gift,
  Star,
  Award,
  CreditCard,
  Leaf,
  type LucideIcon,
} from "lucide-react";

/** Icon names the admin "items" editor can reference (Admin > Homepage Builder). */
export const ICON_MAP: Record<string, LucideIcon> = {
  Hand,
  Droplet,
  ShieldCheck,
  Gem,
  Package,
  Heart,
  Sparkles,
  PenTool,
  Palette,
  Layers,
  PackageCheck,
  Clock,
  Flame,
  Wand2,
  Truck,
  SprayCan,
  Settings2,
  BadgeCheck,
  RotateCcw,
  Headset,
  Crown,
  Gift,
  Star,
  Award,
  CreditCard,
  Leaf,
};

export function resolveIcon(name?: string): LucideIcon {
  return (name && ICON_MAP[name]) || Sparkles;
}
